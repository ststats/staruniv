-- security definer라 admin_users 자체의 RLS 순환을 피한다.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_users a
    where a.user_id = auth.uid()
      and a.is_active = true
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

drop policy if exists "admin_users_read_self" on public.admin_users;
create policy "admin_users_read_self"
on public.admin_users
for select
to authenticated
using (user_id = (select auth.uid()));

grant select on public.admin_users to authenticated;

do $$
declare
  t text;
begin
  foreach t in array array['teams','members','matches','rounds','tier_members','calendar_events','calendar_off_air','site_config','history_entries']
  loop
    execute format('drop policy if exists %I on public.%I', 'admins_all_' || t, t);
    execute format(
      'create policy %I on public.%I for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()))',
      'admins_all_' || t,
      t
    );
  end loop;
end $$;

grant select, insert, update, delete on public.teams, public.members,
  public.matches, public.rounds, public.tier_members, public.calendar_events, public.calendar_off_air, public.site_config, public.history_entries to authenticated;
grant usage, select on all sequences in schema public to authenticated;

do $$
declare
  t text;
begin
  foreach t in array array['elo_categories','elo_maps','elo_players','elo_matches']
  loop
    execute format('drop policy if exists %I on public.%I', 'admins_read_' || t, t);
    execute format(
      'create policy %I on public.%I for select to authenticated using ((select public.is_admin()))',
