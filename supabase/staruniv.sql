drop function if exists public.api_videos();
create or replace function public.api_videos(
  p_channel text default null,
  p_before timestamptz default null,
  p_before_id text default null,
  p_limit integer default 20,
  p_admin boolean default false
) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v_limit integer := greatest(1, least(coalesce(p_limit,20),100)); v_result jsonb;
begin
  if p_admin and not coalesce(public.is_admin(),false) then raise exception 'admin only'; end if;
  with channels as (
    select channel_url,channel_id,title,display_name,thumb,uploads,source_order,active
    from public.video_channels where p_admin or active
  ), eligible as (
    select v.id,v.channel_url,v.title,v.published,v.thumb,v.views,v.short,v.hidden
    from public.videos v join channels c using(channel_url)
    where (p_admin or not v.hidden) and v.id ~ '^[A-Za-z0-9_-]{11}$'
  ), selected as (
    select * from eligible where p_channel is null or channel_url=p_channel
  ), page as (
    select * from selected where not short and
      (p_before_id is null or (coalesce(published,'-infinity'::timestamptz),id)
        < (coalesce(p_before,'-infinity'::timestamptz),p_before_id))
    order by published desc nulls last,id desc limit v_limit+1
  ), shown as (
    select * from page order by published desc nulls last,id desc limit v_limit
  )
  select jsonb_build_object(
    'videos',coalesce((select jsonb_agg(to_jsonb(v) order by published desc nulls last,id desc) from shown v),'[]'::jsonb),
    'next',case when (select count(*) from page)>v_limit then
      (select jsonb_build_object('published',published,'id',id) from shown
       order by published asc nulls first,id asc limit 1) else null end,
    'summary',case when p_before_id is null then jsonb_build_object(
      'channels',coalesce((select jsonb_agg(to_jsonb(c)||jsonb_build_object('count',
        (select count(*) from eligible e where e.channel_url=c.channel_url)) order by source_order) from channels c),'[]'::jsonb),
      'total',(select count(*) from selected where not short),
      'top',coalesce((select jsonb_agg(to_jsonb(v) order by views desc,published desc,id desc) from
        (select * from selected where not short and published>=now()-interval '30 days'
         order by views desc,published desc,id desc limit 3) v),'[]'::jsonb),
      'shorts',coalesce((select jsonb_agg(to_jsonb(v) order by published desc nulls last,id desc) from
        (select * from selected where short order by published desc nulls last,id desc limit 24) v),'[]'::jsonb),
      'picks',coalesce((select jsonb_agg(to_jsonb(v) order by source_order) from (
        select id,kind,title,note,group_name,group_en,author,thumb,short,hidden,source_order
        from public.video_picks where (p_admin or not hidden)
          and id ~ '^([A-Za-z0-9_-]{11}|soop:[0-9]{1,20})$') v),'[]'::jsonb)
    ) else null end
  ) into v_result;
  return v_result;
end;
$$;

