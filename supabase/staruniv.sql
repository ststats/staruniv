  for each row execute function public.normalize_race_columns();


-- ############################################################################
-- 11. 티어 표기 통일(갓 킹 잭 조커 스페이드 0~8 베이비, 미분류는 체크)
-- ############################################################################
-- core.js SITE_ORDER.tiers와 같은 값으로 저장한다('5티어'·god·스페 같은 표기는 묶이지 않아서).
-- 모르는 값은 앞뒤 공백만 지우고 그대로 둔다.
create or replace function public.normalize_tier(v text)
returns text
language sql
immutable
set search_path = public
as $$
  select case
    when t is null then null
    when upper(t) in ('GOD', '갓') then '갓'
    when upper(t) in ('KING', '킹') then '킹'
    when upper(t) in ('JACK', '잭') then '잭'
    when upper(t) in ('JOKER', '조커', '조커요') then '조커'
    when upper(t) in ('SPADE', '스페이드', '스페') then '스페이드'
    when upper(t) in ('BABY', '베이비') then '베이비'
    when upper(t) in ('CHECK', '체크', '체', '미분류') then '체크'
    else t
  end
  from (select nullif(btrim(regexp_replace(btrim(coalesce(v, '')), '\s*티어$', '')), '') as t) x
$$;

create or replace function public.normalize_tier_columns()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_table_name = 'rounds' then
    new.our_tier := public.normalize_tier(new.our_tier);
    new.opponent_tier := public.normalize_tier(new.opponent_tier);
  elsif tg_table_name = 'members' then
    new.tier := public.normalize_tier(new.tier);
    new.join_tier := public.normalize_tier(new.join_tier);
  else
    new.tier := public.normalize_tier(new.tier);
  end if;
  return new;
end;
$$;

drop trigger if exists tier_members_normalize_tier on public.tier_members;
create trigger tier_members_normalize_tier before insert or update of tier on public.tier_members
  for each row execute function public.normalize_tier_columns();
drop trigger if exists members_normalize_tier on public.members;
create trigger members_normalize_tier before insert or update of tier, join_tier on public.members
  for each row execute function public.normalize_tier_columns();
drop trigger if exists rounds_normalize_tier on public.rounds;
create trigger rounds_normalize_tier before insert or update of our_tier, opponent_tier on public.rounds
  for each row execute function public.normalize_tier_columns();

-- 관리자 삭제는 감사 기록과 한 트랜잭션이라 기록이 실패하면 삭제도 롤백된다. 로그인 없는 수집 작업은 건너뛴다.
create or replace function public.audit_admin_delete()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row jsonb := to_jsonb(old);
  v_key text;
begin
  if auth.uid() is null then return old; end if;
  if not public.is_admin() then raise exception 'admin only'; end if;
  v_key := v_row ->> tg_argv[0];
  if tg_nargs = 2 then v_key := v_key || ':' || (v_row ->> tg_argv[1]); end if;
  perform public.admin_write_audit('delete', tg_table_name, v_key, v_row);
  return old;
end;
$$;
revoke all on function public.audit_admin_delete() from public, anon, authenticated;

do $$
declare v_table text; v_key text;
begin
  for v_table, v_key in
    select * from (values
      ('members','id'), ('teams','id'), ('history_entries','id'),
      ('calendar_events','id'), ('holidays','day'), ('matches','match_no'),
      ('university_logos','name'), ('tier_members','id'),
      ('tier_member_elo_links','elo_id'), ('tier_member_candidates','id'),
      ('video_picks','id'), ('external_tools','id')
    ) as targets(table_name, key_column)
  loop
    -- 후보 표는 이 파일 다음에 실행하는 ststat.sql이 만든다
    if v_table = 'tier_member_candidates' and to_regclass('public.tier_member_candidates') is null then
      continue;
    end if;
    execute format('drop trigger if exists admin_delete_audit on public.%I', v_table);
    execute format('create trigger admin_delete_audit after delete on public.%I for each row execute function public.audit_admin_delete(%L)', v_table, v_key);
  end loop;
end;
$$;
drop trigger if exists admin_delete_audit on public.calendar_off_air;
create trigger admin_delete_audit after delete on public.calendar_off_air
  for each row execute function public.audit_admin_delete('off_date', 'soop_id');
