-- 티어표 갱신(반자동): 펨코 티어표 이미지 주소 + FA 명단 글을 넣으면 GitHub Actions가
-- scripts/tier_table.py로 읽어 DB와 비교하고, 결과를 tier_update_jobs.result에 넣는다.
-- 관리자는 결과를 보고 반영할 것만 골라 반영한다(반영 함수는 이 파일 아래쪽).
--
-- 준비: '달력 사진 갱신'과 같은 GitHub 토큰(Vault의 github_actions_token)을 쓴다. 토큰 권한은
--       Actions = Read and write 그대로면 된다. 이 파일 전체를 SQL 편집기에서 한 번 실행한다.
-- 여러 번 실행해도 된다(있는 표·함수는 그대로 두거나 바꿔 쓴다).

create extension if not exists pg_net with schema extensions;

-- 분석 요청과 결과
create table if not exists public.tier_update_jobs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  image_url text not null,
  fa_text text,
  status text not null default 'queued'
    check (status in ('queued', 'running', 'done', 'failed', 'applied')),
  result jsonb,
  error text,
  started_at timestamptz,
  finished_at timestamptz,
  applied_at timestamptz
);
alter table public.tier_update_jobs enable row level security;
drop policy if exists tier_update_jobs_admin_read on public.tier_update_jobs;
create policy tier_update_jobs_admin_read on public.tier_update_jobs
  for select to authenticated using (public.is_admin());
revoke all on public.tier_update_jobs from anon;
grant select on public.tier_update_jobs to authenticated;

