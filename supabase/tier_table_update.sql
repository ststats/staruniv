-- 분석 요청: 작업을 만들고 GitHub Actions(tier-analysis.yml)를 실행한다. 반환값: 작업 번호.
create or replace function public.admin_request_tier_analysis(p_image_url text, p_fa_text text default null)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  token text;
  job_id bigint;
begin
  if not coalesce(public.is_admin(), false) then
    raise exception '관리자만 실행할 수 있습니다.';
  end if;
  -- 펨코 이미지 서버 주소만 받는다(다른 주소를 Actions가 내려받지 않게)
  if p_image_url is null or p_image_url !~ '^https://image\.fmkorea\.com/' then
    raise exception '티어표 이미지 주소는 https://image.fmkorea.com/ 으로 시작해야 합니다.';
  end if;
  select decrypted_secret into token
  from vault.decrypted_secrets where name = 'github_actions_token' limit 1;
  if token is null or token = '' then
    raise exception 'GitHub 토큰(github_actions_token)이 Vault에 없습니다.';
  end if;

  insert into public.tier_update_jobs (image_url, fa_text)
  values (p_image_url, nullif(btrim(coalesce(p_fa_text, '')), ''))
  returning id into job_id;

  perform net.http_post(
    url := 'https://api.github.com/repos/ststats/staruniv/actions/workflows/tier-analysis.yml/dispatches',
    body := jsonb_build_object('ref', 'main', 'inputs', jsonb_build_object('job_id', job_id::text)),
    headers := jsonb_build_object(
      'Authorization', 'Bearer ' || token,
      'Accept', 'application/vnd.github+json',
      'X-GitHub-Api-Version', '2022-11-28',
      'User-Agent', 'staruniv-supabase'
    )
  );
  return job_id;
end;
$$;

revoke all on function public.admin_request_tier_analysis(text, text) from public, anon;
grant execute on function public.admin_request_tier_analysis(text, text) to authenticated;
